#!/usr/bin/env node
/**
 * Bundles the app into one self contained HTML file that works when opened
 * straight from disk (browsers refuse to load ES modules over `file://`).
 *
 *     node tools/build.mjs          write dist/minecraft-stronghold-finder.html
 *     node tools/build.mjs --check  fail if the committed build is stale
 *
 * No dependencies: the module syntax used in src/ is stripped with a tiny
 * scanner and the stylesheet is inlined.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'dist', 'minecraft-stronghold-finder.html');

/** Dependency order: each file only uses names declared before it. */
const MODULES = ['src/java-random.js', 'src/stronghold.js', 'src/triangulate.js', 'src/app.js'];

/**
 * Removes `import` statements, `export { ... }` statements and the `export`
 * keyword so the files can be concatenated into one classic script.
 *
 * @param {string} source
 */
export function stripModuleSyntax(source) {
  const lines = source.split('\n');
  const kept = [];
  let skipping = false;
  for (const line of lines) {
    if (skipping) {
      if (/from\s+['"][^'"]+['"];?\s*$/.test(line) || /\}\s*;?\s*$/.test(line)) skipping = false;
      continue;
    }
    if (/^\s*import\b/.test(line)) {
      const closesOnThisLine = /from\s+['"][^'"]+['"];?\s*$/.test(line) || /^\s*import\s+['"][^'"]+['"];?\s*$/.test(line);
      skipping = !closesOnThisLine;
      continue;
    }
    if (/^\s*export\s*\{/.test(line)) {
      skipping = !/\}\s*;?\s*$/.test(line);
      continue;
    }
    kept.push(line.replace(/^(\s*)export\s+(?=(?:const|let|var|function|class|async)\b)/, '$1'));
  }
  return kept.join('\n');
}

/** @param {string} source */
function assertParseable(source) {
  // Compiles without running, so DOM access is irrelevant here.
  new vm.Script(source, { filename: 'bundle.js' });
}

function build() {
  const html = readFileSync(path.join(root, 'index.html'), 'utf8');
  const css = readFileSync(path.join(root, 'assets', 'style.css'), 'utf8');
  const script = `(function () {\n"use strict";\n\n${bundleCode()}\n})();`;
  assertParseable(script);

  let output = html
    .replace(
      /<link rel="stylesheet" href="assets\/style\.css">/,
      `<style>\n${css.trim()}\n</style>`,
    )
    .replace(
      /<script type="module" src="src\/app\.js"><\/script>/,
      `<script>\n${script}\n</script>`,
    );

  output = output.replace(
    '<title>',
    '<!-- Generated by tools/build.mjs - edit the files in src/, assets/ and index.html instead. -->\n<title>',
  );

  if (!output.includes('===== src/app.js =====')) {
    throw new Error('bundling failed: the app module was not injected');
  }
  if (!output.includes('<style>')) {
    throw new Error('bundling failed: the stylesheet was not inlined');
  }
  return output;
}

/**
 * The application code as one classic script body (module syntax stripped).
 * Shared with the UI smoke test so both use exactly the same source.
 *
 * @returns {string}
 */
export function bundleCode() {
  return MODULES.map((file) => {
    const source = readFileSync(path.join(root, file), 'utf8');
    return `/* ===== ${file} ===== */\n${stripModuleSyntax(source).trim()}`;
  }).join('\n\n');
}

function main() {
  const expected = build();

  if (process.argv.includes('--check')) {
    if (!existsSync(outputPath)) {
      console.error('dist/minecraft-stronghold-finder.html is missing - run: npm run build');
      process.exitCode = 1;
    } else if (readFileSync(outputPath, 'utf8') !== expected) {
      console.error('dist/minecraft-stronghold-finder.html is out of date - run: npm run build');
      process.exitCode = 1;
    } else {
      console.log('dist/minecraft-stronghold-finder.html is up to date');
    }
  } else {
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, expected);
    const kilobytes = (Buffer.byteLength(expected) / 1024).toFixed(1);
    console.log(`wrote dist/minecraft-stronghold-finder.html (${kilobytes} KiB)`);
  }
}

// Only run when invoked as a script, so the test suite can import the helpers.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
