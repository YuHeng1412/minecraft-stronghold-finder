/**
 * Seed based stronghold placement.
 *
 * The ring arithmetic is a 1:1 port of the vanilla algorithm
 * (`ChunkGenerator.generateStrongholds` on 1.9 - 1.18, and
 * `ChunkGeneratorStructureState.generateRingPositions` on 1.19.3+), which the
 * C library `cubiomes` mirrors as well.
 *
 * From 1.9 on, Minecraft lays out up to 128 strongholds in concentric rings
 * around the origin. Each one is first placed on an ideal point - the centre of
 * a chunk on a ring - and is then nudged (at most 112 blocks) to the nearest
 * biome that may hold a stronghold. This module reproduces the ideal point,
 * which is the point a thrown Eye of Ender aims at, so results are accurate to
 * roughly 112 blocks and are an excellent start for eye triangulation.
 *
 * Two versions of the algorithm exist, and the difference decides whether the
 * whole layout can be predicted from the seed alone:
 *
 *  - 1.19.3 and newer fork a private random for the biome search
 *    (`randomsource.fork()`, which consumes exactly one `nextLong()` from the
 *    ring generator), so every angle and distance stays deterministic. All 128
 *    ideal points can be computed offline.
 *
 *  - 1.9 - 1.19.2 hand the *shared* ring generator to the biome search, which
 *    draws a random number for every accepted biome it finds - roughly two
 *    thousand draws per stronghold. Everything after the first stronghold
 *    therefore depends on the terrain, and knowing it requires generating the
 *    biomes of the world. Only the first stronghold is predictable here, and
 *    this module deliberately reports just that one instead of inventing the
 *    rest.
 */

import { JavaRandom, isNumericSeed, parseSeed } from './java-random.js';

/** Chunk distance of the innermost ring, in chunks (4 * 32). */
const RING_BASE_DISTANCE = 128;
/** Random spread of the ring distance, in chunks (32 * 2.5). */
const RING_DISTANCE_SPREAD = 80;

/**
 * Stronghold rings: how many strongholds the ring holds and how far from the
 * origin (in blocks) they lie. The first seven rings follow a triangular
 * pattern, the eighth is capped so that a world never holds more than 128.
 */
export const RINGS = Object.freeze([
  { ring: 1, count: 3, min: 1408, max: 2688 },
  { ring: 2, count: 6, min: 4480, max: 5760 },
  { ring: 3, count: 10, min: 7552, max: 8832 },
  { ring: 4, count: 15, min: 10624, max: 11904 },
  { ring: 5, count: 21, min: 13696, max: 14976 },
  { ring: 6, count: 28, min: 16768, max: 18048 },
  { ring: 7, count: 36, min: 19840, max: 21120 },
  { ring: 8, count: 9, min: 22912, max: 24192 },
]);

/** Total number of strongholds generated by a 1.9+ world. */
export const TOTAL_STRONGHOLDS = 128;

/** Largest distance from the origin a stronghold can have, in blocks. */
export const MAX_STRONGHOLD_RADIUS = RINGS[RINGS.length - 1].max;

/**
 * Supported placement generations.
 *
 * `model` describes where the biome search takes its randomness from:
 * `forked` (a private generator, the ring stream stays intact) or `shared`
 * (the ring generator itself, so later positions are unknowable without
 * generating biomes). `predictableCount` is how many ideal points this module
 * can honestly report for that model.
 */
export const VERSIONS = Object.freeze([
  {
    id: 'modern',
    label: '1.19.3 - 1.21.x',
    aliases: [
      '1.19.3', '1.19.4', '1.20', '1.20.1', '1.20.2', '1.20.3', '1.20.4', '1.20.5', '1.20.6',
      '1.21', '1.21.1', '1.21.2', '1.21.3', '1.21.4', '1.21.5', '1.21.6', '1.21.7', '1.21.8',
      'modern', 'latest',
    ],
    model: 'forked',
    count: TOTAL_STRONGHOLDS,
    predictableCount: TOTAL_STRONGHOLDS,
  },
  {
    id: 'classic',
    label: '1.9 - 1.19.2',
    aliases: [
      '1.9', '1.9.4', '1.10', '1.11', '1.12', '1.13', '1.14', '1.15', '1.16', '1.16.5',
      '1.17', '1.18', '1.18.2', '1.19', '1.19.1', '1.19.2', 'classic',
    ],
    model: 'shared',
    count: TOTAL_STRONGHOLDS,
    predictableCount: 1,
  },
  {
    id: 'legacy',
    label: '1.8 and older',
    aliases: ['1.8', '1.8.9', '1.7', '1.6', '1.5', '1.4', '1.3', '1.2', '1.1', '1.0', 'beta', 'legacy'],
    model: 'legacy',
    count: 3,
    predictableCount: 1,
  },
]);

/**
 * Accepts a version id ("modern"), a Minecraft version ("1.20.4") or a partial
 * version ("1.20") and returns the matching placement definition.
 *
 * @param {string} [input]
 */
export function resolveVersion(input = 'modern') {
  const key = String(input).trim().toLowerCase();
  if (!key) return VERSIONS[0];
  for (const version of VERSIONS) {
    if (version.id === key || version.aliases.includes(key)) return version;
  }
  const match = /^(\d+)\.(\d+)(?:\.(\d+))?$/.exec(key);
  if (match) {
    const major = Number(match[1]);
    const minor = Number(match[2]);
    const patch = match[3] === undefined ? null : Number(match[3]);
    if (major === 1 && minor <= 8) return VERSIONS[2];
    // 1.19 without a patch version means the 1.19 series as people run it
    // today, which is 1.19.3+; 1.19.1/1.19.2 are matched exactly above.
    if (major === 1 && minor === 19) return VERSIONS[0];
    if (major === 1 && minor >= 20) return VERSIONS[0];
    if (major === 1 && minor >= 9) return VERSIONS[1];
    if (major > 1) return VERSIONS[0];
  }
  throw new RangeError(`Unknown Minecraft version: ${input}`);
}

/**
 * Distance band (blocks from the origin) of a ring.
 *
 * @param {number} ring 1-based ring number
 * @returns {{min: number, max: number}|null}
 */
export function ringRange(ring) {
  const entry = RINGS[ring - 1];
  return entry ? { min: entry.min, max: entry.max } : null;
}

/**
 * Which ring a distance from the origin belongs to, or null when it falls
 * between rings.
 *
 * @param {number} radius
 * @returns {number|null}
 */
export function ringOf(radius) {
  for (const entry of RINGS) {
    if (radius >= entry.min && radius <= entry.max) return entry.ring;
  }
  return null;
}

/**
 * The ring whose band is closest to `radius` (useful when a triangulated point
 * is a few blocks outside a band because of measurement error).
 *
 * @param {number} radius
 * @returns {number}
 */
export function nearestRing(radius) {
  let best = 1;
  let bestDistance = Infinity;
  for (const entry of RINGS) {
    const delta = radius < entry.min ? entry.min - radius : radius > entry.max ? radius - entry.max : 0;
    if (delta < bestDistance) {
      bestDistance = delta;
      best = entry.ring;
    }
  }
  return best;
}

/**
 * Turns an angle/distance pair (in chunks) into the ideal stronghold position,
 * matching vanilla's `Math.round(cos(angle) * dist) * 16 + 8`.
 *
 * @param {number} angle radians
 * @param {number} dist chunk distance from the origin
 */
function positionFrom(angle, dist) {
  const chunkX = Math.round(Math.cos(angle) * dist);
  const chunkZ = Math.round(Math.sin(angle) * dist);
  return {
    chunkX,
    chunkZ,
    // The chunk centre: this is the point a thrown Eye of Ender aims at.
    x: chunkX * 16 + 8,
    z: chunkZ * 16 + 8,
    // The starting staircase of a stronghold sits at (4, 4) inside its chunk.
    staircaseX: chunkX * 16 + 4,
    staircaseZ: chunkZ * 16 + 4,
  };
}

/**
 * Builds the stronghold layout for a world seed.
 *
 * @param {number|bigint|string} seedInput
 * @param {{version?: string}} [options]
 * @returns {{
 *   seed: string,
 *   textSeed: boolean,
 *   version: string,
 *   versionLabel: string,
 *   model: 'forked'|'shared',
 *   fullyPredictable: boolean,
 *   predictableCount: number,
 *   totalCount: number,
 *   note: string|null,
 *   strongholds: Array<object>
 * }}
 */
export function generateStrongholds(seedInput, options = {}) {
  const version = resolveVersion(options.version ?? 'modern');
  const seed = parseSeed(seedInput);
  const random = new JavaRandom(seed);
  const strongholds = [];

  if (version.model === 'legacy') {
    // 1.8 and older: three strongholds on a wide arc. Only the first one is
    // predictable, because the biome search then eats into the shared stream.
    const angle = 2 * Math.PI * random.nextDouble();
    const dist = (1.25 + random.nextDouble()) * 32;
    strongholds.push(makeStronghold(0, 1, angle, dist, false));
  } else if (version.model === 'shared') {
    // 1.9 - 1.19.2: the ring layout is the same, but every stronghold after
    // the first depends on how many biomes the search accepts.
    const angle = 2 * Math.PI * random.nextDouble();
    const dist = RING_BASE_DISTANCE + (random.nextDouble() - 0.5) * RING_DISTANCE_SPREAD;
    strongholds.push(makeStronghold(0, 1, angle, dist, true));
  } else {
    let angle = 2 * Math.PI * random.nextDouble();
    let dist = RING_BASE_DISTANCE + (random.nextDouble() - 0.5) * RING_DISTANCE_SPREAD;
    let ring = 0;
    let ringIndex = 0;
    let ringMax = 3;
    let index = 0;

    while (index < TOTAL_STRONGHOLDS) {
      strongholds.push(makeStronghold(index, ring + 1, angle, dist, true));

      // Vanilla forks the ring generator for the biome search of this
      // stronghold, which advances the shared stream by one long.
      random.nextLong();

      ringIndex++;
      angle += (2 * Math.PI) / ringMax;
      if (ringIndex === ringMax) {
        ring++;
        ringIndex = 0;
        ringMax = ringMax + Math.floor((2 * ringMax) / (ring + 1));
        if (ringMax > TOTAL_STRONGHOLDS - index) ringMax = TOTAL_STRONGHOLDS - index;
        // Each ring starts at a fresh, randomly rotated angle.
        angle += random.nextDouble() * Math.PI * 2;
      }
      dist = RING_BASE_DISTANCE + 6 * ring * 32 + (random.nextDouble() - 0.5) * RING_DISTANCE_SPREAD;
      index++;
    }
  }

  const fullyPredictable = version.model === 'forked';
  return {
    seed: seed.toString(),
    textSeed: !isNumericSeed(seedInput),
    version: version.id,
    versionLabel: version.label,
    model: version.model,
    fullyPredictable,
    predictableCount: strongholds.length,
    totalCount: version.count,
    note: fullyPredictable ? null : 'shared-biome-stream',
    strongholds,
  };
}

/**
 * @param {number} index 0-based global index
 * @param {number} ring 1-based ring number
 * @param {number} angle radians
 * @param {number} dist chunk distance
 * @param {boolean} rings whether the world uses the ring layout
 */
function makeStronghold(index, ring, angle, dist, rings) {
  const position = positionFrom(angle, dist);
  const distance = Math.hypot(position.x, position.z);
  const range = rings ? ringRange(ring) : null;
  let bearing = (Math.atan2(position.x, position.z) * 180) / Math.PI;
  if (bearing < 0) bearing += 360;
  return {
    index: index + 1,
    ring,
    ringCount: rings ? RINGS[ring - 1].count : 3,
    // Distances are in blocks; `chunkDistance` is the raw ring distance.
    chunkDistance: dist,
    angle,
    bearing,
    distance,
    ringRange: range,
    chunkX: position.chunkX,
    chunkZ: position.chunkZ,
    x: position.x,
    z: position.z,
    staircaseX: position.staircaseX,
    staircaseZ: position.staircaseZ,
  };
}

/**
 * Convenience helper: only the strongholds of one ring.
 *
 * @param {number|bigint|string} seedInput
 * @param {number} ring
 * @param {{version?: string}} [options]
 */
export function strongholdsInRing(seedInput, ring, options = {}) {
  return generateStrongholds(seedInput, options).strongholds.filter((entry) => entry.ring === ring);
}

/**
 * How many blocks (worst case) the real stronghold staircase can sit away from
 * the reported ideal point, because vanilla relocates it to a valid biome.
 */
export const RELOCATION_RADIUS = 112;
